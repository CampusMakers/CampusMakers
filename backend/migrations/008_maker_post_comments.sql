begin;

create table if not exists public.maker_post_comments (
    id bigint generated by default as identity primary key,
    post_id bigint not null references public.maker_posts(id) on delete cascade,
    parent_id bigint references public.maker_post_comments(id) on delete cascade,
    author_id uuid not null references auth.users(id) on delete cascade,
    author text not null,
    content text not null check (char_length(btrim(content)) between 1 and 1000),
    created_at timestamptz not null default now()
);

create index if not exists maker_post_comments_post on public.maker_post_comments (post_id, created_at, id);

create or replace function public.prepare_maker_post_comment()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
    profile public.messaging_profiles;
    target_post public.maker_posts;
    parent_post_id bigint;
    parent_parent_id bigint;
begin
    if auth.uid() is null or new.author_id <> auth.uid() then
        raise exception 'Sign in to comment.';
    end if;
    select * into profile from public.messaging_profiles where id = auth.uid();
    if not found then raise exception 'A confirmed account is required to comment.'; end if;
    new.author := '@' || profile.username;
    new.content := btrim(new.content);
    if new.parent_id is not null then
        select post_id, parent_id into parent_post_id, parent_parent_id
        from public.maker_post_comments where id = new.parent_id;
        if not found or parent_post_id <> new.post_id or parent_parent_id is not null then
            raise exception 'Replies must belong to a comment on this post.';
        end if;
        select * into target_post from public.maker_posts where id = new.post_id;
        if not found or not public.is_verified_maker() or not (
            target_post.seller_id = auth.uid() or exists (
                select 1 from jsonb_array_elements_text(target_post.collaborators) member
                where lower(ltrim(member, '@')) = lower(profile.username)
            )
        ) then raise exception 'Only the seller or a seller collaborator can reply.'; end if;
    end if;
    return new;
end;
$$;

drop trigger if exists prepare_maker_post_comment on public.maker_post_comments;
create trigger prepare_maker_post_comment before insert on public.maker_post_comments
for each row execute function public.prepare_maker_post_comment();

alter table public.maker_post_comments enable row level security;
revoke all on public.maker_post_comments from anon, authenticated;
grant select on public.maker_post_comments to anon, authenticated;
grant insert (post_id, parent_id, author_id, content) on public.maker_post_comments to authenticated;
grant delete on public.maker_post_comments to authenticated;
grant usage, select on sequence public.maker_post_comments_id_seq to authenticated;

drop policy if exists maker_post_comments_read on public.maker_post_comments;
create policy maker_post_comments_read on public.maker_post_comments for select to anon, authenticated using (true);
drop policy if exists maker_post_comments_insert on public.maker_post_comments;
create policy maker_post_comments_insert on public.maker_post_comments for insert to authenticated with check (author_id = auth.uid());
drop policy if exists maker_post_comments_delete on public.maker_post_comments;
create policy maker_post_comments_delete on public.maker_post_comments for delete to authenticated using (author_id = auth.uid());

commit;
